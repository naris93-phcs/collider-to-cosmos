C     Functionality to handling grid
C     



      DOUBLE PRECISION FUNCTION DSIG14_VEC(ALL_PP, ALL_XBK, ALL_Q2FACT
     $ , ALL_CM_RAP, ALL_WGT, IMODE, ALL_OUT, SYMCONF, CONFSUB,
     $  ICONF_VEC, IMIRROR_VEC, VECSIZE_USED)
C     ****************************************************
C     
C     Generated by MadGraph5_aMC@NLO v. 3.8.0, 2026-09-15
C     By the MadGraph5_aMC@NLO Development Team
C     Visit launchpad.net/madgraph5 and amcatnlo.web.cern.ch
C     
C     Process: d~ s~ > w+ w+ u~ c~ QCD=0 QED<=4 @1
C     *   Decay: w+ > e+ ve WEIGHTED<=2
C     *   Decay: w+ > mu+ vm WEIGHTED<=2
C     
C     RETURNS DIFFERENTIAL CROSS SECTION
C     Input:
C     pp    4 momentum of external particles
C     wgt   weight from Monte Carlo
C     imode 0 run, 1 init, 2 reweight, 
C     3 finalize, 4 only PDFs,
C     5 squared amplitude only (never
C     generate events)
C     Output:
C     Amplitude squared and summed
C     ****************************************************
      IMPLICIT NONE
C     
C     CONSTANTS
C     
      INCLUDE '../../Source/vector.inc'  ! defines VECSIZE_MEMMAX
      INCLUDE 'genps.inc'
      INCLUDE 'nexternal.inc'
      INCLUDE 'maxconfigs.inc'
      INCLUDE 'maxamps.inc'
      DOUBLE PRECISION       CONV
      PARAMETER (CONV=389379.66*1000)  !CONV TO PICOBARNS
      REAL*8     PI
      PARAMETER (PI=3.1415926D0)
C     
C     ARGUMENTS 
C     
      DOUBLE PRECISION ALL_PP(0:3,NEXTERNAL,VECSIZE_MEMMAX)
      DOUBLE PRECISION ALL_WGT(VECSIZE_MEMMAX)
      DOUBLE PRECISION ALL_XBK(2,VECSIZE_MEMMAX)
      DOUBLE PRECISION ALL_Q2FACT(2,VECSIZE_MEMMAX)
      DOUBLE PRECISION ALL_CM_RAP(VECSIZE_MEMMAX)
      INTEGER IMODE
      DOUBLE PRECISION ALL_OUT(VECSIZE_MEMMAX)
      INTEGER IMIRROR_VEC(*)
      INTEGER ICONF_VEC(*)
      INTEGER VECSIZE_USED
      INTEGER SYMCONF(0:LMAXCONFIGS)
      INTEGER CONFSUB(MAXSPROC,LMAXCONFIGS)
C     ----------
C     BEGIN CODE
C     ----------
C     
C     LOCAL VARIABLES 
C     
      INTEGER I,ITYPE,LP,IPROC
      DOUBLE PRECISION QSCALE
      DOUBLE PRECISION DX1(VECSIZE_MEMMAX)
      DOUBLE PRECISION SX2(VECSIZE_MEMMAX)
      DOUBLE PRECISION XPQ(-7:7),PD(0:MAXPROC)
      DOUBLE PRECISION ALL_PD(0:MAXPROC, VECSIZE_MEMMAX)
      DOUBLE PRECISION DSIGUU,R,RCONF
      INTEGER LUN,ICONF,IFACT,NFACT
      DATA NFACT/1/
      SAVE NFACT
      DOUBLE PRECISION RHEL  ! random number
      INTEGER CHANNEL
C     
C     STUFF FOR DRESSED EE COLLISIONS
C     
      INCLUDE '../../Source/PDF/eepdf.inc'
      DOUBLE PRECISION EE_COMP_PROD

      INTEGER I_EE
C     
C     STUFF FOR UPC
C     
      DOUBLE PRECISION PHOTONPDFSQUARE
C     
C     EXTERNAL FUNCTIONS
C     
      LOGICAL PASSCUTS
      DOUBLE PRECISION ALPHAS2,REWGT,PDG2PDF,CUSTOM_BIAS
      INTEGER NEXTUNOPEN
      DOUBLE PRECISION DSIG14
C     
C     GLOBAL VARIABLES
C     
      INTEGER          IPSEL
      COMMON /SUBPROC/ IPSEL
C     MINCFIG has this config number
      INTEGER           MINCFIG, MAXCFIG
      COMMON/TO_CONFIGS/MINCFIG, MAXCFIG
      INTEGER MAPCONFIG(0:LMAXCONFIGS), ICONFIG
      COMMON/TO_MCONFIGS/MAPCONFIG, ICONFIG
C     Keep track of whether cuts already calculated for this event
      LOGICAL CUTSDONE,CUTSPASSED
      COMMON/TO_CUTSDONE/CUTSDONE,CUTSPASSED

      INTEGER SUBDIAG(MAXSPROC),IB(2)
      COMMON/TO_SUB_DIAG/SUBDIAG,IB
      INCLUDE 'run.inc'

      DOUBLE PRECISION P_MULTI(0:3, NEXTERNAL, VECSIZE_MEMMAX)
      DOUBLE PRECISION HEL_RAND(VECSIZE_MEMMAX)
      DOUBLE PRECISION COL_RAND(VECSIZE_MEMMAX)
      INTEGER SELECTED_HEL(VECSIZE_MEMMAX)
      INTEGER SELECTED_COL(VECSIZE_MEMMAX)
      DOUBLE PRECISION ALL_RWGT(VECSIZE_MEMMAX)

C     Common blocks
      INCLUDE '../../Source/PDF/pdf.inc'
C     CHARACTER*7         PDLABEL,EPA_LABEL
C     INTEGER       LHAID
C     COMMON/TO_PDF/LHAID,PDLABEL,EPA_LABEL     

C     
C     local
C     
      DOUBLE PRECISION P1(0:3, NEXTERNAL)
      INTEGER IVEC, CURR_WARP, IWARP, NB_WARP_USED
      INTEGER CHANNELS(VECSIZE_MEMMAX)
C     Per-event MLM graph: igraphs(1) from REWGT (0 = no MLM)
      INTEGER IGRAPH(VECSIZE_MEMMAX)
      COMMON/VEC_IGRAPH/IGRAPH
C     
C     DATA
C     
      DATA DX1/VECSIZE_MEMMAX*1D0/
      DATA SX2/VECSIZE_MEMMAX*1D0/
C     ----------
C     BEGIN CODE
C     ----------
      SELECTED_HEL(:) = 0
      SELECTED_COL(:) = 0

      IF(IMODE.EQ.1)THEN
        NFACT = DSIG14(ALL_PP(0,1,1), ALL_WGT(1), IMODE)
        RETURN
      ENDIF

C     Continue only if IMODE is 0, 4 or 5
      IF(IMODE.NE.0.AND.IMODE.NE.4.AND.IMODE.NE.5) RETURN


      NB_WARP_USED = VECSIZE_USED / WARP_SIZE
      IF( NB_WARP_USED * WARP_SIZE .NE. VECSIZE_USED ) THEN
        WRITE(*,*) 'ERROR: NB_WARP_USED * WARP_SIZE .NE. VECSIZE_USED',
     &    NB_WARP_USED, WARP_SIZE, VECSIZE_USED
        STOP
      ENDIF

      DO CURR_WARP=1, NB_WARP_USED
        IF(IMIRROR_VEC(CURR_WARP).EQ.1)THEN
          IB(1) = 1
          IB(2) = 2
        ELSE
          IB(1) = 2
          IB(2) = 1
        ENDIF
        DO IWARP=1, WARP_SIZE
          IVEC = (CURR_WARP-1)*WARP_SIZE+IWARP
          IF (ABS(LPP(IB(1))).GE.1) THEN
C           LP=SIGN(1,LPP(IB(1)))
            DX1(IVEC)=PDG2PDF(LPP(IB(1)),-1, IB(1),ALL_XBK(IB(1),IVEC)
     $       ,DSQRT(ALL_Q2FACT(1, IVEC)))
          ENDIF
          IF (ABS(LPP(IB(2))).GE.1) THEN
C           LP=SIGN(1,LPP(IB(2)))
            SX2(IVEC)=PDG2PDF(LPP(IB(2)),-3, IB(2),ALL_XBK(IB(2),IVEC)
     $       ,DSQRT(ALL_Q2FACT(2, IVEC)))
          ENDIF
        ENDDO  ! IWARP LOOP
      ENDDO  ! CURRWARP LOOP
      ALL_PD(0,:) = 0D0
      IPROC = 0
      IPROC=IPROC+1  ! d~ s~ > e+ ve mu+ vm u~ c~
      DO IVEC=1, VECSIZE_USED
        ALL_PD(IPROC,IVEC)=DX1(IVEC)*SX2(IVEC)
        ALL_PD(0,IVEC)=ALL_PD(0,IVEC)+DABS(ALL_PD(IPROC,IVEC))

      ENDDO


      IF (IMODE.EQ.4)THEN
        ALL_OUT(:) = ALL_PD(0,:)
        RETURN
      ENDIF

      DO CURR_WARP=1, NB_WARP_USED
        IF(IMIRROR_VEC(CURR_WARP).EQ.1)THEN
          IB(1) = 1
          IB(2) = 2
        ELSE
          IB(1) = 2
          IB(2) = 1
        ENDIF
        DO IWARP=1, WARP_SIZE
          IVEC = (CURR_WARP-1)*WARP_SIZE+IWARP
C         Do not need those three here. do I?	 
          XBK(:) = ALL_XBK(:,IVEC)
C         CM_RAP = ALL_CM_RAP(IVEC)
          Q2FACT(:) = ALL_Q2FACT(:, IVEC)


C         Select a flavor combination (need to do here for right sign)
          CALL RANMAR(R)
          IPSEL=0
          DO WHILE (R.GE.0D0 .AND. IPSEL.LT.IPROC)
            IPSEL=IPSEL+1
            R=R-DABS(ALL_PD(IPSEL,IVEC))/ALL_PD(0,IVEC)
          ENDDO

          CHANNELS(IVEC) = CONFSUB(14,SYMCONF(ICONF_VEC(CURR_WARP)))
          SUBDIAG(14) = CHANNELS(IVEC)  ! only valid if a single process
          CHANNEL = SUBDIAG(14)


          ALL_RWGT(IVEC) = REWGT(ALL_PP(0,1,IVEC), IVEC)

          IF(FRAME_ID.NE.6)THEN
            CALL BOOST_TO_FRAME(ALL_PP(0,1,IVEC), FRAME_ID, P_MULTI(0
     $       ,1,IVEC))
          ELSE
            P_MULTI(:,:,IVEC) = ALL_PP(:,:,IVEC)
          ENDIF
          CALL RANMAR(HEL_RAND(IVEC))
          CALL RANMAR(COL_RAND(IVEC))
        ENDDO  ! end loop on IWARP/IVEC	 
      ENDDO  ! end loop on the CURR_WARP
      CALL SMATRIX14_MULTI(P_MULTI, HEL_RAND, COL_RAND, CHANNELS,
     $  IGRAPH, ALL_OUT , SELECTED_HEL, SELECTED_COL, VECSIZE_USED)


      DO CURR_WARP=1, NB_WARP_USED
        IF(IMIRROR_VEC(CURR_WARP).EQ.1)THEN
          IB(1) = 1
          IB(2) = 2
        ELSE
          IB(1) = 2
          IB(2) = 1
        ENDIF
        DO IWARP=1, WARP_SIZE
          IVEC = (CURR_WARP-1)*WARP_SIZE+IWARP
          DSIGUU = ALL_OUT(IVEC)
          IF (IMODE.EQ.5) THEN
            IF (DSIGUU.LT.1D199) THEN
              ALL_OUT(IVEC) = DSIGUU*CONV
            ELSE
              ALL_OUT(IVEC) = 0.0D0
            ENDIF
            RETURN
          ENDIF

          XBK(:) = ALL_XBK(:,IVEC)
C         CM_RAP = ALL_CM_RAP(IVEC)
          Q2FACT(:) = ALL_Q2FACT(:, IVEC)

          IF(FRAME_ID.NE.6)THEN
            CALL BOOST_TO_FRAME(ALL_PP(0,1,IVEC), FRAME_ID, P1)
          ELSE
            P1 = ALL_PP(:,:,IVEC)
          ENDIF
C         call restore_cl_val_to(ivec)
C         DSIGUU=DSIGUU*REWGT(P1,ivec)
          DSIGUU=DSIGUU*ALL_RWGT(IVEC)

C         Apply the bias weight specified in the run card (default is
C          1.0)
          DSIGUU=DSIGUU*CUSTOM_BIAS(P1,DSIGUU,14, IVEC)

          DSIGUU=DSIGUU*NFACT

          IF (DSIGUU.LT.1D199) THEN
C           Set sign of dsig based on sign of PDF and matrix element
            ALL_OUT(IVEC)=DSIGN(CONV*ALL_PD(0,IVEC)*DSIGUU,DSIGUU
     $       *ALL_PD(IPSEL,IVEC))
          ELSE
            WRITE(*,*) 'Error in matrix element'
            DSIGUU=0D0
            ALL_OUT(IVEC)=0D0
          ENDIF
C         Generate events only if IMODE is 0.
          IF(IMODE.EQ.0.AND.DABS(ALL_OUT(IVEC)).GT.0D0)THEN
C           Call UNWGT to unweight and store events
            ICONFIG = SYMCONF(ICONF_VEC(CURR_WARP))
            CALL UNWGT(ALL_PP(0,1,IVEC), ALL_OUT(IVEC)*ALL_WGT(IVEC)
     $       ,14, SELECTED_HEL(IVEC), SELECTED_COL(IVEC), IVEC)
          ENDIF
        ENDDO
      ENDDO

      END




