        AMP2(85)=AMP2(85)+AMP(85)*DCONJG(AMP(85))
        AMP2(86)=AMP2(86)+AMP(86)*DCONJG(AMP(86))
      ENDIF

      DO I = 1, NCOLOR
        DO M = 1, NAMPSO
          DO N = 1, NAMPSO

            JAMP2(I)=JAMP2(I)+DABS(DBLE(JAMP(I,M)*DCONJG(JAMP(I,N))))

          ENDDO
        ENDDO
      ENDDO

